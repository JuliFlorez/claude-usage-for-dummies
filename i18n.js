// "es-419" → "es"; si no lo tenemos, inglés.
function pickLang(tag) {
  const base = String(tag || "").toLowerCase().split(/[-_]/)[0];
  return I18N[base] ? base : "en";
}

// T(lang) devuelve el diccionario completo de ese idioma.
function T(lang) {
  return I18N[pickLang(lang)];
}

// Duración corta, igual en todos los idiomas: "2 d 3 h", "3 h 5 min", "5 min".
function fmtDuration(minutes) {
  const m = Math.max(0, Math.round(minutes));
  const d = Math.floor(m / 1440), h = Math.floor((m % 1440) / 60), mm = m % 60;
  if (d) return `${d} d ${h} h`;
  if (h) return `${h} h ${mm} min`;
  return `${mm} min`;
}

// 48213 → "48k", 1200000 → "1,2M" (con el separador decimal del idioma).
function fmtTokens(n, lang) {
  const loc = String(lang || "en");
  if (n >= 1e6) return (n / 1e6).toLocaleString(loc, { maximumFractionDigits: 1 }) + "M";
  if (n >= 1e3) return Math.round(n / 1e3).toLocaleString(loc) + "k";
  return String(Math.round(n));
}
